// Writes src/styles/_fonts.scss: the @font-face rules of the theme fonts, Latin and Latin Extended
// subsets only (French needs nothing else). Run again after updating a @fontsource-variable package:
//   npm run fonts:generate
import { readFileSync, writeFileSync } from 'node:fs';

/** Package and variable axis file of each font offered in core/theme/theme-fonts.ts. */
const SOURCES = [
  ['fraunces', 'opsz.css'],
  ['fraunces', 'opsz-italic.css'],
  ['playfair-display', 'wght.css'],
  ['playfair-display', 'wght-italic.css'],
  ['cormorant-garamond', 'wght.css'],
  ['cormorant-garamond', 'wght-italic.css'],
  ['dancing-script', 'wght.css'],
  ['quicksand', 'wght.css'],
  ['bodoni-moda', 'opsz.css'],
  ['bodoni-moda', 'opsz-italic.css'],
  ['cinzel', 'wght.css'],
  ['eb-garamond', 'wght.css'],
  ['eb-garamond', 'wght-italic.css'],
  ['caveat', 'wght.css'],
  ['comfortaa', 'wght.css'],
  ['inter', 'wght.css'],
  ['nunito', 'wght.css'],
  ['dm-sans', 'wght.css'],
  ['source-sans-3', 'wght.css'],
  ['lora', 'wght.css'],
  ['open-sans', 'wght.css'],
  ['montserrat', 'wght.css'],
  ['work-sans', 'wght.css'],
  ['manrope', 'wght.css'],
  ['merriweather', 'opsz.css'],
];
const KEPT_SUBSET = /-latin(-ext)?-/;
const OUTPUT = 'src/styles/_fonts.scss';

let scss = `// Self-hosted fonts of the themes (Fontsource, SIL Open Font License), see core/theme/theme-fonts.ts.
// Latin and Latin Extended subsets only: French needs nothing else, and the other alphabets would
// only weigh down the stylesheet. Browsers download a file only when a page uses its font.
// Generated by scripts/generate-fonts.mjs (npm run fonts:generate): do not edit by hand.
`;

for (const [pkg, file] of SOURCES) {
  const css = readFileSync(`node_modules/@fontsource-variable/${pkg}/${file}`, 'utf8');
  // One block per subset, each preceded by a /* name */ comment
  for (const block of css.split(/\n(?=\/\*)/)) {
    const name = block.match(/\/\* (\S+) \*\//)?.[1];
    if (!name || !KEPT_SUBSET.test(name)) {
      continue;
    }
    scss +=
      '\n' +
      block
        .trim()
        .replace('url(./files/', `url('../../node_modules/@fontsource-variable/${pkg}/files/`)
        .replace('.woff2)', ".woff2')") +
      '\n';
  }
}

writeFileSync(OUTPUT, scss);
console.log(`${OUTPUT}: ${scss.match(/@font-face/g).length} @font-face rules`);
